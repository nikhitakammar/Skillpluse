"""Rule-based learner practice suggestions for trainer review."""

from datetime import date

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.api.deps import get_db
from app.models import Assessment, AssessmentResult, Student
from app.schemas.recommendations import SkillRecommendation, StudentRecommendations
from app.security.auth import current_user
from app.security.scopes import student_skill_access, trainer_skill_scope

router = APIRouter(prefix="/students", tags=["learning recommendations"])

SUGGESTIONS = {
    "python": "Practice a short set of Python exercises focused on the concepts from recent checkpoints, then review one solution with a trainer.",
    "sql": "Practice writing queries with filters, joins and aggregates, then compare the results with a trainer-provided answer.",
    "problem solving": "Break a small task into steps, explain the approach, and compare it with an alternative solution during trainer review.",
    "communication": "Give a short explanation of a recent project or concept and ask a peer or trainer for feedback on clarity.",
}
NOTICE = (
    "These practice suggestions are simple benchmark-based prompts from synthetic demonstration records. "
    "They are not generated by the prediction model; trainers should discuss and adapt them with the learner."
)


@router.get("/{student_id}/recommendations", response_model=StudentRecommendations)
def student_recommendations(
    student_id: str,
    benchmark: float = Query(default=70, ge=0, le=100),
    skill_area: str | None = Query(default=None, max_length=80),
    user=Depends(current_user),
    db: Session = Depends(get_db),
) -> StudentRecommendations:
    if db.get(Student, student_id) is None:
        raise HTTPException(status_code=404, detail="Student not found")
    allowed_skills = student_skill_access(db, user, student_id)
    if skill_area and allowed_skills is not None and skill_area.casefold() not in {item.casefold() for item in allowed_skills}:
        raise HTTPException(status_code=403, detail="This trainer is not assigned to that learner's subject")

    query = (
        select(
            Assessment.skill_area,
            func.avg(AssessmentResult.score / Assessment.max_score * 100),
            func.count(AssessmentResult.result_id),
        )
        .join(Assessment, Assessment.assessment_id == AssessmentResult.assessment_id)
        .where(
            AssessmentResult.student_id == student_id,
            Assessment.assessment_date <= date.today(),
        )
        .group_by(Assessment.skill_area)
    )
    query = trainer_skill_scope(query, user, AssessmentResult.student_id, Assessment.skill_area)
    if allowed_skills is not None:
        query = query.where(Assessment.skill_area.in_(allowed_skills))
    if skill_area:
        query = query.where(func.lower(Assessment.skill_area) == skill_area.casefold())
    rows = db.execute(query).all()

    eligible = [
        (skill_area, float(average), int(count))
        for skill_area, average, count in rows
        if count >= 2
    ]
    if not eligible:
        return StudentRecommendations(
            student_id=student_id,
            status="insufficient_data",
            benchmark=benchmark,
            recommendations=[],
            message="At least two recorded assessments in a skill area are needed to suggest focused practice.",
            notice=NOTICE,
        )

    gaps = sorted(
        (item for item in eligible if item[1] < benchmark),
        key=lambda item: item[1],
    )[:3]
    recommendations = [
        SkillRecommendation(
            skill_area=skill_area,
            average_score=round(average, 2),
            assessment_count=count,
            benchmark=benchmark,
            suggestion=SUGGESTIONS.get(
                skill_area.casefold(),
                f"Review recent {skill_area} assessment topics and agree on one focused practice activity with a trainer.",
            ),
            reason=f"Average score is {average:.1f}% across {count} assessments, below the {benchmark:g}% review benchmark.",
        )
        for skill_area, average, count in gaps
    ]
    message = (
        "Review these skill areas with the learner and adapt the practice to their goals."
        if recommendations
        else "No eligible assessed skill area is below the selected review benchmark."
    )
    return StudentRecommendations(
        student_id=student_id,
        status="ready",
        benchmark=benchmark,
        recommendations=recommendations,
        message=message,
        notice=NOTICE,
    )
